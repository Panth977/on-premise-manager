UPGRADE_ONLY="${v.UPGRADE_ONLY}"; SEEN_IP="${v.SEEN_IP}"; GUI_UPGRADE="${v.GUI_UPGRADE}"
SKIP_DOCKER="\${OPM_SKIP_DOCKER_INSTALL:-0}"; DRY="\${DRY_RUN:-0}"
