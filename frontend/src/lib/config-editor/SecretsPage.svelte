<script lang="ts">
  import type { SecretDef, SecretDefInput } from '@opm/shared';
  import ScopeHeader from './ScopeHeader.svelte';
  import Button from '../ui/Button.svelte';
  import EmptyState from '../ui/EmptyState.svelte';
  import SearchInput from '../ui/SearchInput.svelte';
  import ConfirmDialog from '../ui/ConfirmDialog.svelte';
  import Modal from '../ui/Modal.svelte';
  import Field from '../ui/Field.svelte';
  import RevealValue from '../ui/RevealValue.svelte';
  import RelTime from '../ui/RelTime.svelte';
  import Menu, { type MenuItem } from '../ui/Menu.svelte';
  import Icon from '../ui/Icon.svelte';
  import { Plus, Pencil, Trash2, KeyRound, RefreshCw, Lock, X, Wand2 } from '../ui/icons';
  import SecretDrawer from './SecretDrawer.svelte';
  import SecretValueInput, { secretValueError } from '$opm/forms/secrets/SecretValueInput.svelte';
  import DraftBanner from './DraftBanner.svelte';
  import { secretRefs } from './refs';
  import { catalog } from '../stores/catalog.svelte';
  import { api } from '../api';
  import type { AnyScope } from './scope.svelte';

  let { scope }: { scope: AnyScope } = $props();
  const isDep = $derived(scope.kind === 'deployment');
  const canReveal = $derived(scope.kind === 'deployment' && scope.can('deployment.secrets', 'read'));
  const setSlugs = $derived(scope.kind === 'deployment' ? (scope.secretsSet ?? []) : []);
  /** §21 #105: the value of the head commit (Reveal shows it); a pending op shows "not committed" */
  const headSet = (s: SecretDef) => !!scope.baseConfig.secrets.find((x) => x.secretSlug === s.secretSlug)?.value;
  const opText = (s: SecretDef) => {
    const op = scope.secretPending(s.secretSlug);
    if (!op) return null;
    return op.generateNow ? 'generated at commit' : op.plainValue === null || op.plainValue === '' ? 'cleared — not committed' : 'new value — not committed';
  };
  let q = $state('');
  const rows = $derived(scope.config.secrets.filter((s) => !q || `${s.secretSlug} ${s.label} ${s.description}`.toLowerCase().includes(q.toLowerCase())));
  const source = (s: SecretDef) => (s.generate ? `generate ${s.generate.charset} ${s.generate.length}` : 'a person enters it');
  const isSet = (s: SecretDef) => setSlugs.includes(s.secretSlug);
  /** bumped when a value is replaced from this page (set / generate / clear) → its RevealValue masks again */
  let maskKeys = $state<Record<string, number>>({});
  const bump = (slug: string) => (maskKeys[slug] = (maskKeys[slug] ?? 0) + 1);

  // drawer
  let drawerOpen = $state(false);
  let editing = $state<SecretDef | null>(null);
  // set value modal (1 field)
  let setOpen = $state(false);
  let target = $state<SecretDef | null>(null);
  let value = $state('');
  const valErr = $derived(secretValueError(value));
  let touched = $state(false);
  function openSet(s: SecretDef) {
    target = s;
    value = '';
    touched = false;
    setOpen = true;
  }
  function inputs(mod: (s: SecretDefInput) => SecretDefInput): SecretDefInput[] {
    return scope.secretInputs().map(mod);
  }
  async function saveValue(e: Event) {
    e.preventDefault();
    touched = true;
    if (valErr || !target) return;
    const slug = target.secretSlug;
    if (await scope.saveSection('secrets', inputs((s) => (s.secretSlug === slug ? { ...s, plainValue: value } : s)), `Value of ${slug} applied`)) {
      bump(slug);
      value = '';
      setOpen = false;
    }
  }
  // confirms
  let genOpen = $state(false);
  let clearOpen = $state(false);
  let rmOpen = $state(false);
  const rmRefs = $derived(target && rmOpen ? secretRefs(scope.working(), target.secretSlug, (id) => catalog.slugOf(id)) : []);
  async function doGenerate() {
    const slug = target!.secretSlug;
    bump(slug);
    return scope.saveSection('secrets', inputs((s) => (s.secretSlug === slug ? { ...s, generateNow: true } : s)), `${slug}: a new value is generated by the commit`);
  }
  async function doClear() {
    const slug = target!.secretSlug;
    bump(slug);
    return scope.saveSection('secrets', inputs((s) => (s.secretSlug === slug ? { ...s, plainValue: null } : s)), `Value of ${slug} cleared (not committed)`);
  }
  async function doRemove() {
    const slug = target!.secretSlug;
    if (scope.kind === 'template')
      return scope.saveSection(
        'secrets',
        scope.config.secrets.filter((s) => s.secretSlug !== slug).map((s) => ({ ...($state.snapshot(s) as SecretDef), value: null })),
        `Secret ${slug} removed`,
      );
    return scope.saveSection('secrets', scope.secretInputs().filter((s) => s.secretSlug !== slug), `Secret ${slug} removed`);
  }
  function menu(s: SecretDef): MenuItem[] {
    const items: MenuItem[] = [];
    if (isDep) {
      items.push({ label: isSet(s) ? 'Set a new value' : 'Set value', icon: KeyRound, onclick: () => openSet(s), testid: 'm-set' });
      if (s.generate) items.push({ label: 'Generate new', icon: Wand2, onclick: () => ((target = s), (genOpen = true)), testid: 'm-generate' });
      if (isSet(s)) items.push({ label: 'Clear value', icon: X, onclick: () => ((target = s), (clearOpen = true)), testid: 'm-clear' });
      items.push({ divider: true, label: '' });
    }
    items.push({ label: 'Edit definition', icon: Pencil, onclick: () => ((editing = s), (drawerOpen = true)), testid: 'm-edit' });
    items.push({ label: 'Remove', icon: Trash2, danger: true, onclick: () => ((target = s), (rmOpen = true)), testid: 'm-remove' });
    return items;
  }
</script>

{#if isDep}<DraftBanner deploymentId={scope.id} />{/if}
<ScopeHeader kind={scope.kind} title="Secrets" subtitle={isDep ? 'Values are stored masked; View shows the committed value for 60 s and is logged. Set / Generate / Clear are changes like any other: kept in this browser (typed values in memory only, never stored) until Commit….' : 'Templates never hold secret values. Each deployment generates or receives its own.'} icon={Lock} readOnly={!scope.canWriteSecrets}>
  {#snippet actions()}
    <SearchInput bind:value={q} placeholder="Search secrets" width="220px" />
    {#if scope.canWriteSecrets}<Button variant="primary" icon={Plus} onclick={() => ((editing = null), (drawerOpen = true))} data-testid="add-secret">Add secret</Button>{/if}
  {/snippet}
</ScopeHeader>

{#if !scope.config.secrets.length}
  <EmptyState icon={Lock} title="No secrets" text="Secrets are passwords, tokens and keys. Containers use them with secretRef, {'{{ secret.<slug> }}'} or a secret volume.">
    {#snippet action()}{#if scope.canWriteSecrets}<Button variant="primary" icon={Plus} onclick={() => ((editing = null), (drawerOpen = true))}>Add secret</Button>{/if}{/snippet}
  </EmptyState>
{:else if !rows.length}
  <EmptyState compact title="No match" text="No secret matches “{q}”." />
{:else}
  <div class="table-wrap">
    <table class="table" data-testid="secrets-table">
      <thead>
        <tr>
          <th>Slug</th><th>Label</th><th>Required</th><th>Value source</th>
          {#if isDep}<th>State</th><th>Rotated</th><th>Value</th>{:else}<th>Description</th><th>Value</th>{/if}
          <th class="actions"><span class="sr-only">Actions</span></th>
        </tr>
      </thead>
      <tbody>
        {#each rows as s (s.secretSlug)}
          <tr data-testid="sec-row-{s.secretSlug}">
            <td class="mono">{s.secretSlug}</td>
            <td>{s.label}{#if isDep && s.description}<div class="xs faint">{s.description}</div>{/if}</td>
            <td>{#if s.required}<span class="badge blue">required</span>{:else}<span class="faint small">optional</span>{/if}</td>
            <td class="small">{#if s.generate}<span class="badge violet"><Icon icon={Wand2} size={11} />{source(s)}</span>{:else}<span class="muted">{source(s)}</span>{/if}</td>
            {#if isDep}
              <td>
                {#if opText(s)}<span class="badge amber" data-testid="pending-{s.secretSlug}"><span class="dot"></span>{opText(s)}</span>
                {:else if isSet(s)}<span class="badge green"><span class="dot"></span>set</span>
                {:else}<span class="badge {s.required ? 'red' : 'gray'}" data-testid="not-set-{s.secretSlug}"><span class="dot"></span>not set{s.required ? ' — blocks a commit' : ''}</span>{/if}
              </td>
              <td class="small muted"><RelTime ts={s.rotatedAt} /></td>
              <td>
                <RevealValue
                  testid="reveal-{s.secretSlug}"
                  isSet={headSet(s)}
                  {canReveal}
                  lengthHint={s.generate?.length ?? null}
                  maskKey={maskKeys[s.secretSlug] ?? 0}
                  reveal={() => api.revealSecret({ deploymentId: scope.id, secretSlug: s.secretSlug })}
                />
              </td>
            {:else}
              <td class="small muted">{s.description || '—'}</td>
              <td class="small faint" data-testid="tpl-value-{s.secretSlug}">set per deployment</td>
            {/if}
            <td class="actions">
              {#if scope.canWriteSecrets}
                {#if isDep}<Button size="sm" icon={KeyRound} onclick={() => openSet(s)} data-testid="set-{s.secretSlug}">{isSet(s) ? 'Set new' : 'Set value'}</Button>{/if}
                <Menu items={menu(s)} label="Actions for {s.secretSlug}" testid="menu-{s.secretSlug}" />
              {/if}
            </td>
          </tr>
        {/each}
      </tbody>
    </table>
  </div>
{/if}

<SecretDrawer bind:open={drawerOpen} {scope} secret={editing} />

<Modal bind:open={setOpen} title="Set the value of {target?.secretSlug}" subtitle="Kept in this browser's memory only (never stored) until Commit…; the sites get it after a person there merges the commit." size="sm" busy={scope.saving} testid="set-secret-modal">
  <form id="set-form" onsubmit={saveValue} novalidate>
    <Field label="Value" id="sv" required hint="≤ 8 KiB. Masked afterwards; View shows it for 60 s (logged).">
      {#if target}<SecretValueInput id="sv" value={value} onchange={(v) => (value = v ?? '')} secret={target} submitted={touched} testid="secret-value" />{/if}
    </Field>
  </form>
  {#snippet footer()}
    <Button onclick={() => (setOpen = false)} disabled={scope.saving}>Cancel</Button>
    <Button type="submit" form="set-form" variant="primary" loading={scope.saving} disabled={touched && !!valErr} data-testid="secret-save">Apply value</Button>
  {/snippet}
</Modal>

<ConfirmDialog bind:open={genOpen} title="Generate a new value for {target?.secretSlug}?" message="The commit generates a new random value ({target?.generate?.charset} {target?.generate?.length}) — View it after the commit. Containers get it after a person on the site merges the commit; the old value keeps working until then." confirmLabel="Generate at commit" onconfirm={doGenerate} testid="generate-secret" />
<ConfirmDialog bind:open={clearOpen} title="Clear the value of {target?.secretSlug}?" message={target?.required ? 'The secret is required: a commit is blocked until it has a value again.' : 'The secret has no value afterwards.'} confirmLabel="Clear value" danger onconfirm={doClear} testid="clear-secret" />
<ConfirmDialog bind:open={rmOpen} title="Remove secret {target?.secretSlug}?" confirmLabel="Remove" danger onconfirm={doRemove} testid="remove-secret">
  {#snippet body()}
    {#if rmRefs.length}
      <div class="banner warn small"><div><b>Used in {rmRefs.length} place{rmRefs.length === 1 ? '' : 's'}</b> — a commit is blocked until you fix them:<ul class="refs">{#each rmRefs.slice(0, 8) as r, i (i)}<li><span class="mono xs">{r.path}</span> <span class="faint xs">{r.value}</span></li>{/each}</ul></div></div>
    {:else}<p class="muted">Nothing uses this secret.</p>{/if}
  {/snippet}
</ConfirmDialog>

<style>
  .refs {
    margin: 6px 0 0;
    padding-left: 16px;
  }
</style>
