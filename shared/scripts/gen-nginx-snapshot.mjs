// Generates testdata/nginx-import-snapshot.json: importNginx(testdata/client-nginx.conf, CONTAINERS) with the containers
// the fixture's upstreams name. nginx-import.test.ts deep-equals the importer output with it.
// Regenerate only deliberately, and eyeball the printed mapping table first:
//   npm run build && node scripts/gen-nginx-snapshot.mjs [--check]
import { readFileSync, writeFileSync } from 'node:fs';
import assert from 'node:assert/strict';
import { importNginx } from '../dist/nginx-import.js';

const http = (containerSlug, port) => ({ containerSlug, ports: [{ portName: 'http', port, edge: true }] });
const containers = [
  ...['ez-integration', 'ez-dc', 'ez-worker', 'ez-pg-listen', 'ez-terminal', 'ez-migrate', 'ez-admin', 'ez-heatmap'].map((c) => http(c, 8080)),
  http('northwind-admin', 3000),
  http('pg-admin', 80),
  http('nodered', 1880),
  http('northwind-web', 80),
];
const text = readFileSync(new URL('../testdata/client-nginx.conf', import.meta.url), 'utf8');
const result = importNginx(text, { containers });

const pad = (s, n) => (s.length > n ? s.slice(0, n - 1) + '…' : s.padEnd(n));
for (const r of result.rows) console.log(`${String(r.line).padStart(3)} ${pad(r.text, 58)} ${pad(r.status, 11)} ${pad(r.target ?? '—', 52)} ${r.note}`);
console.log(result.summary);

const doc = {
  _doc: 'importNginx(testdata/client-nginx.conf, {containers}) — generated by shared/scripts/gen-nginx-snapshot.mjs; asserted by src/nginx-import.test.ts.',
  containers,
  result,
};
const file = new URL('../testdata/nginx-import-snapshot.json', import.meta.url);
if (process.argv.includes('--check')) {
  assert.deepEqual(JSON.parse(readFileSync(file, 'utf8')), JSON.parse(JSON.stringify(doc)));
  console.log('snapshot unchanged');
} else {
  writeFileSync(file, JSON.stringify(doc, null, 2) + '\n');
  console.log(`nginx-import-snapshot.json: ${result.rows.length} rows, ${result.edge.routes.length} routes`);
}
